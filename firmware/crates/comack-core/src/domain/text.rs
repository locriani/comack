//! Bitmap text for the e-paper: a hand-drawn 5x7 ASCII font rasterised
//! straight into a [`Frame`], the same 1-bit buffer the Epd7in5 panel
//! displays, so text costs no new dependency and no driver change.
//!
//! Glyph rows are bytes, most significant bit = leftmost column, a set
//! bit is ink. A set frame bit is white, so the renderer clears bits and
//! text drawn on a blank (all-white) frame comes out black on white.

use super::{Frame, FRAME_HEIGHT, FRAME_WIDTH};

/// Glyph width in pixels.
pub const GLYPH_WIDTH: usize = 5;

/// Glyph height in pixels.
pub const GLYPH_HEIGHT: usize = 7;

/// Horizontal distance between glyph origins: the glyph plus one
/// tracking pixel.
pub const CHAR_ADVANCE: usize = GLYPH_WIDTH + 1;

/// Draws `text` in black starting with its first glyph's top-left pixel
/// at (`x`, `y`). Characters outside printable ASCII advance silently;
/// glyphs clip at the frame edges instead of wrapping or panicking.
pub fn draw_text(frame: &mut Frame, x: usize, y: usize, text: &str) {
    for (position, ch) in text.chars().enumerate() {
        let glyph_x = x + position * CHAR_ADVANCE;
        if glyph_x >= FRAME_WIDTH {
            break;
        }
        draw_glyph(frame, glyph_x, y, ch);
    }
}

/// The 5x7 rows for a printable ASCII character, or `None` outside
/// `0x20..=0x7E`.
pub fn glyph(ch: char) -> Option<&'static [u8; GLYPH_HEIGHT]> {
    let index = u8::try_from(ch as u32).ok()?.checked_sub(0x20)?;
    if index > 0x7E - 0x20 {
        return None;
    }
    Some(&FONT_5X7[usize::from(index)])
}

fn draw_glyph(frame: &mut Frame, x: usize, y: usize, ch: char) {
    let Some(rows) = glyph(ch) else {
        return;
    };
    for (row, bits) in rows.iter().enumerate() {
        let pixel_y = y + row;
        if pixel_y >= FRAME_HEIGHT {
            return;
        }
        for column in 0..GLYPH_WIDTH {
            // Bit 4 is the glyph's leftmost column.
            if bits & (1 << (GLYPH_WIDTH - 1 - column)) == 0 {
                continue;
            }
            let pixel_x = x + column;
            if pixel_x >= FRAME_WIDTH {
                break;
            }
            clear_pixel(frame, pixel_x, pixel_y);
        }
    }
}

/// One bit per pixel, row-major, most significant bit first, set = white
/// (see `Frame`): text ink is black, so drawing clears the bit.
fn clear_pixel(frame: &mut Frame, x: usize, y: usize) {
    let pixel = y * FRAME_WIDTH + x;
    let shift = 7 - (pixel % 8);
    frame[pixel / 8] &= !(1 << shift);
}

