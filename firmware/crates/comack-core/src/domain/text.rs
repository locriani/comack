#[cfg(test)]
mod tests {
    use super::*;
    use crate::domain::{FRAME_BYTES, FRAME_WIDTH};

    /// The first byte of row `y`: it holds pixels `x = 0..8`.
    fn row_byte(frame: &Frame, y: usize) -> u8 {
        frame[y * FRAME_WIDTH / 8]
    }

    #[test]
    fn a_is_five_columns_of_ink() {
        let mut frame: Frame = [0xFF; FRAME_BYTES];
        draw_text(&mut frame, 0, 0, "A");
        assert_eq!(row_byte(&frame, 0), 0x8F);
        assert_eq!(row_byte(&frame, 1), 0x77);
        assert_eq!(row_byte(&frame, 3), 0x07);
        assert_eq!(row_byte(&frame, 6), 0x77);
        assert_eq!(frame[1], 0xFF);
    }

    #[test]
    fn text_advances_six_pixels_per_glyph() {
        let mut frame: Frame = [0xFF; FRAME_BYTES];
        draw_text(&mut frame, 0, 0, "AA");
        assert_eq!(row_byte(&frame, 0), 0x8E);
        assert_eq!(frame[1], 0x3F);
    }

    #[test]
    fn glyphs_clip_at_the_right_edge() {
        let mut frame: Frame = [0xFF; FRAME_BYTES];
        draw_text(&mut frame, FRAME_WIDTH - 3, 0, "A");
        // Row 0 loses ink beyond x=799.
        assert_eq!(frame[99], 0xFC);
        // Row 1's left column inks x=797, in row 1's own last byte.
        assert_eq!(frame[199], 0xFB);
        // Nothing wrapped from row 0 into row 1's first byte.
        assert_eq!(frame[100], 0xFF);
    }

    #[test]
    fn glyphs_clip_at_the_bottom_edge() {
        let mut frame: Frame = [0xFF; FRAME_BYTES];
        draw_text(&mut frame, 0, FRAME_HEIGHT - 2, "A");
        // Only the glyph's top rows are on the panel.
        let last_row = (FRAME_HEIGHT - 1) * FRAME_WIDTH / 8;
        assert_eq!(frame[last_row], 0x77);
        // Nothing wrapped past the last row (no byte after it).
        assert_eq!(frame.len(), last_row + FRAME_WIDTH / 8);
    }

    #[test]
    fn off_frame_text_changes_nothing() {
        let mut frame: Frame = [0xFF; FRAME_BYTES];
        draw_text(&mut frame, FRAME_WIDTH, 0, "A");
        draw_text(&mut frame, 0, FRAME_HEIGHT, "A");
        assert!(frame.iter().all(|&byte| byte == 0xFF));
    }

    #[test]
    fn non_ascii_advances_without_inking() {
        let mut frame: Frame = [0xFF; FRAME_BYTES];
        draw_text(&mut frame, 0, 0, "éA");
        // 'é' advances silently; 'A' lands one cell over, unclipped.
        assert_eq!(row_byte(&frame, 0), 0xFE);
        assert_eq!(frame[1], 0x3F);
    }

    #[test]
    fn glyph_lookup_outside_ascii_is_none() {
        assert!(glyph('é').is_none());
        assert!(glyph('\u{7F}').is_none());
        assert!(glyph(' ').is_some());
        assert!(glyph('~').is_some());
    }
}
